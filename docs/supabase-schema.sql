-- 1. Bảng users (Quản lý tài khoản và Phân quyền ADMIN / USER)
CREATE TABLE IF NOT EXISTS public.users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name       TEXT NOT NULL,
    email           TEXT NOT NULL UNIQUE,
    password_hash   TEXT NOT NULL,
    password_salt   TEXT NOT NULL,
    role            TEXT NOT NULL DEFAULT 'USER' CHECK (role IN ('ADMIN', 'USER')),
    status          TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'disabled')),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_users_email ON public.users (LOWER(email));
CREATE INDEX IF NOT EXISTS idx_users_role ON public.users (role);

-- 2. Bảng categories (Danh mục video)
CREATE TABLE IF NOT EXISTS public.categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT NOT NULL UNIQUE,
    description TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. Bảng videos (Danh sách video và metadata)
CREATE TABLE IF NOT EXISTS public.videos (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           TEXT NOT NULL,
    description     TEXT,
    thumbnail_url   TEXT,
    file_name       TEXT,
    file_path       TEXT,
    mime_type       TEXT,
    file_size_bytes BIGINT NOT NULL DEFAULT 0 CHECK (file_size_bytes >= 0),
    views           BIGINT NOT NULL DEFAULT 0 CHECK (views >= 0),
    category_id     BIGINT REFERENCES public.categories(id) ON UPDATE CASCADE ON DELETE SET NULL,
    status          TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'draft', 'archived')),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_videos_title ON public.videos (title);
CREATE INDEX IF NOT EXISTS idx_videos_views ON public.videos (views DESC);
CREATE INDEX IF NOT EXISTS idx_videos_category ON public.videos (category_id);
CREATE INDEX IF NOT EXISTS idx_videos_created_at ON public.videos (created_at);

-- 4. Bảng video_view_stats (Thống kê lượt xem theo ngày/tháng)
CREATE TABLE IF NOT EXISTS public.video_view_stats (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    video_id    BIGINT NOT NULL REFERENCES public.videos(id) ON DELETE CASCADE,
    view_date   TEXT NOT NULL, -- YYYY-MM-DD
    views       BIGINT NOT NULL DEFAULT 0 CHECK (views >= 0),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (video_id, view_date)
);

CREATE INDEX IF NOT EXISTS idx_view_stats_date ON public.video_view_stats (view_date);
CREATE INDEX IF NOT EXISTS idx_view_stats_video ON public.video_view_stats (video_id);

